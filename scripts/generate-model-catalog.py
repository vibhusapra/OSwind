#!/usr/bin/env python3
"""Compile reviewed pinned catalogs into Swift; runtime needs no source checkout."""
import argparse,json,pathlib
root=pathlib.Path(__file__).resolve().parents[1];p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
items=[]
for kind,file in [('parakeet','parakeet-v3-coreml.json'),('speakers','speaker-community1-coreml.json')]:
    value=json.loads((root/'models'/file).read_text());body=json.dumps(value,ensure_ascii=False,separators=(',',':'),sort_keys=True)
    assert '"""#' not in body and '\\#(' not in body
    items.append('        .'+kind+': #"""\n'+body+'\n"""#')
text='// Generated by scripts/generate-model-catalog.py; edit models/*.json instead.\nimport Foundation\nextension NativeModelManifest {\n    static let embeddedJSON:[NativeModelKind:String] = [\n'+',\n'.join(items)+'\n    ]\n}\n'
output=root/'Sources/OSwindCore/NativeModelCatalog.generated.swift'
if a.check:
    if not output.exists() or output.read_text()!=text:raise SystemExit('Native catalog generated source is stale; run scripts/generate-model-catalog.py')
else:output.write_text(text)
