#!/usr/bin/env python3
"""Compile pinned preparation-tool and bundled-script hashes; never downloads."""
import argparse,hashlib,json,pathlib
root=pathlib.Path(__file__).resolve().parent.parent
paths=['scripts/convert-visual-model.py','scripts/convert-visual-model.py.lock','models/siglip2-source.json','ThirdParty/Apache-2.0.txt','ThirdParty/VisualPreparation/UV-LICENSE-MIT.txt']
value=json.loads((root/'models/visual-preparation-runtime.json').read_text())
value['assets']=[dict(path=p,bytes=(root/p).stat().st_size,sha256=hashlib.sha256((root/p).read_bytes()).hexdigest()) for p in paths]
encoded=json.dumps(value,sort_keys=True,separators=(',',':'))
source='// Generated by scripts/visual-preparation-catalog.py; do not edit.\nimport Foundation\n\nenum VisualPreparationCatalog {\n    static let json = #"'+encoded+'"#\n}\n'
target=root/'Sources/OSwindCore/VisualPreparationCatalog.swift'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
if args.check:
 if not target.exists() or target.read_text()!=source:raise SystemExit('Visual preparation catalog is stale; regenerate it')
else:target.write_text(source)
print('Checked' if args.check else 'Compiled','pinned runtime and',len(paths),'asset hashes')
