#!/usr/bin/env python3
"""Independent GLiNER/Rust tokenizer references; no weights or inference.

Use the PII experiment's locked CPython3.12 environment. Reads only authored
validation text plus boundary fixtures. Does not read reserved test predictions.
"""
import os
os.environ.update(HF_HUB_OFFLINE='1',TRANSFORMERS_OFFLINE='1',HF_HUB_DISABLE_IMPLICIT_TOKEN='1',TOKENIZERS_PARALLELISM='false')
import argparse,hashlib,json,pathlib,sys,unicodedata,importlib.metadata,inspect

ROOT=pathlib.Path(__file__).resolve().parents[1]
def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def put(path,body):
    path.parent.mkdir(parents=True,exist_ok=True)
    if path.exists():
        if path.read_bytes()!=body:raise ValueError('Existing reference differs: '+path.name)
    else:
        with path.open('xb') as stream:stream.write(body)
def ranges():
    # Python3.12 re \w = Unicode alphanumeric plus underscore. Freeze it so
    # macOS/Swift Unicode database upgrades cannot silently change word IDs.
    result=[];start=None
    for value in range(0x110000):
        member=chr(value).isalnum() or value==95
        if member and start is None:start=value
        if start is not None and (not member or value==0x10ffff):
            result.append((start,value-1 if not member else value));start=None
    return result
def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--model',required=True,type=pathlib.Path);parser.add_argument('--corpus',required=True,type=pathlib.Path);parser.add_argument('--output',required=True,type=pathlib.Path);parser.add_argument('--word-table',type=pathlib.Path);args=parser.parse_args()
    if sys.version_info[:2]!=(3,12) or unicodedata.unidata_version!='15.0.0':raise ValueError('Use pinned CPython3.12 Unicode15.0 reference')
    manifest=json.loads((ROOT/'models/gliner-pii-edge-source.json').read_text());plan=json.loads((ROOT/'benchmarks/prototypes/pii/plan-v6.json').read_text())
    for name,version in plan['runtimePins'].items():
        if importlib.metadata.version(name)!=version:raise ValueError('Pinned tokenizer reference environment differs')
    for item in manifest['modelFiles']:
        if item['path'] in ['tokenizer.json','tokenizer_config.json','gliner_config.json'] and sha(args.model/item['path'])!=item['sha256']:raise ValueError('Pinned tokenizer/config differs')
    if sha(args.corpus)!=plan['corpusSHA256']:raise ValueError('Authored corpus differs')
    table=ranges()
    if args.word_table:
        source='// Generated by prepare-pii-tokenizer-eval.py; Python3.12 Unicode15.0 re \\w.\nimport Foundation\n\nenum PIIWordCharacters {\n    static let ranges:[(UInt32,UInt32)] = [\n'+''.join(f'        (0x{a:x},0x{b:x}),\n' for a,b in table)+'    ]\n    static func contains(_ value:UInt32)->Bool {\n        var low=0,high=ranges.count\n        while low<high {let middle=(low+high)/2;if ranges[middle].1<value {low=middle+1}else {high=middle}}\n        return low<ranges.count && ranges[low].0<=value\n    }\n}\n'
        put(args.word_table,source.encode())
    from transformers import AutoTokenizer
    from gliner.config import GLiNERConfig
    from gliner.data_processing.processor import UniEncoderTokenProcessor
    from gliner.data_processing.tokenizer import WhitespaceTokenSplitter
    tokenizer=AutoTokenizer.from_pretrained(str(args.model.resolve()),local_files_only=True,token=False)
    config=GLiNERConfig(**json.loads((args.model/'gliner_config.json').read_text()));processor=UniEncoderTokenProcessor(config,tokenizer,None);splitter=WhitespaceTokenSplitter();labels=list(plan['labels'])
    rows=[{'id':r['id'],'text':r['text']} for r in json.loads(args.corpus.read_text())['rows'] if r['split']=='validation']
    authored=['a-b','a--b','_a_foo-bar','\ufeffCafe\u0301 👩🏽‍💻 Å Å','中文𠀀カタカナ 한글','api_key: sk-owned-abc123','<<ENT>> [CLS] <<SEP>> [unused1]','e\u0301 a\u0308 \u0301','İ ı ß ẞ ﬀ ﬁ ² Ⅳ ½','A\0B\u200dC\u200cD','x\u1c89y \U0001e4d0name','\u0600\u0627\u064e\u200d\u0628','a\r\nb\tc','👍🏽🏳️‍🌈👨‍👩‍👧‍👦','email owned.person@example.test end','user@example.com password=OwnedOnly-42!']
    whitespace=[*range(9,14),*range(28,33),0x85,0xa0,0x1680,*range(0x2000,0x200b),0x2028,0x2029,0x202f,0x205f,0x3000]
    authored += ['left'+chr(value)+'right' for value in whitespace]
    # Deterministic mixed-script, combining, number and punctuation sequences.
    alphabet=['a','é','e\u0301','中文','𠀀','Ж','\u1c89','ᚠ','𝟠','Ⅻ','²','_','-','!','\u200d','\ufeff','👍🏽']
    authored += [' '.join(alphabet[(i*7+j*3)%len(alphabet)] for j in range(1+i%12)) for i in range(64)]
    rows += [{'id':'boundary-'+str(i),'text':text} for i,text in enumerate(authored)]
    for row in rows:
        text=row['text'];words=list(splitter(text));surfaces=[x[0] for x in words]
        prompted,skip=processor.prepare_inputs([surfaces],labels);encoded=tokenizer(prompted,is_split_into_words=True,truncation=False,padding=False);mask=processor.prepare_word_mask([surfaces],encoded,skip)[0]
        row.update(words=[{'text':w,'location':len(text[:a].encode('utf-16-le'))//2,'length':len(text[a:b].encode('utf-16-le'))//2} for w,a,b in words],inputIDs=encoded['input_ids'][0],attentionMask=encoded['attention_mask'][0],wordsMask=mask,textLength=len(words))
        if len(row['inputIDs'])>512:raise ValueError('Reference exceeds native short-input contract')
    payload={'format':'OSwind PII native tokenizer reference v1','unicodeVersion':unicodedata.unidata_version,'modelRevision':manifest['modelRevision'],'corpusSHA256':sha(args.corpus),'tokenizerSHA256':sha(args.model/'tokenizer.json'),'tokenizerConfigSHA256':sha(args.model/'tokenizer_config.json'),'generatorSHA256':sha(pathlib.Path(__file__)),'glinerProcessorSHA256':sha(pathlib.Path(inspect.getfile(UniEncoderTokenProcessor))),'runtimePins':plan['runtimePins'],'labels':labels,'wordClassRanges':table,'rows':rows,'modelInference':False,'reservedTestPredictionsOpened':False}
    body=(json.dumps(payload,ensure_ascii=False,separators=(',',':'))+'\n').encode();put(args.output,body);print(json.dumps({'rows':len(rows),'wordRanges':len(table),'SHA256':hashlib.sha256(body).hexdigest(),'modelInference':False}))
if __name__=='__main__':main()
