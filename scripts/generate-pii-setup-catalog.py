#!/usr/bin/env python3
"""Embed the pinned native PII setup recipe; no checkout/assets needed at runtime."""
import argparse
import hashlib
import json
from pathlib import Path

root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check",action="store_true")
options=parser.parse_args()
catalog=json.loads((root/"models/pii-native-setup.json").read_text())
catalog["modelLicense"]=(root/"ThirdParty/Apache-2.0.txt").read_text()
body=json.dumps(catalog,ensure_ascii=False,sort_keys=True,separators=(",",":"))
assert '"""#' not in body and '\\#(' not in body
build=hashlib.sha256(body.encode()).hexdigest()
output=root/"Sources/OSwindCore/PIISetupCatalog.generated.swift"
text='// Generated by scripts/generate-pii-setup-catalog.py.\nimport Foundation\nextension PIISetupCatalog {\n    static let buildID="'+build+'"\n    static let embeddedJSON = #"""\n'+body+'\n"""#\n}\n'
if options.check:
    if not output.exists() or output.read_text()!=text:raise SystemExit("PII setup catalog is stale; run scripts/generate-pii-setup-catalog.py")
else:output.write_text(text)
