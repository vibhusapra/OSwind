import Foundation
import CryptoKit

/// Enabling collection is independent of screen/audio capture. Normal launch
/// may resume this explicit choice; quiet restore always clears it.
public struct ClipboardConfiguration:Codable,Equatable,Sendable {
    public var enabled=false
    public init() {}
}

public struct ClipboardTextSnapshot:Sendable {
    public let changeCount:Int
    public let finalChangeCount:Int
    public let itemCount:Int
    public let types:[String]
    public let text:Data
    public let declaredSource:String?
    public init(changeCount:Int,finalChangeCount:Int,itemCount:Int,types:[String],text:Data,declaredSource:String?=nil) {
        self.changeCount=changeCount;self.finalChangeCount=finalChangeCount;self.itemCount=itemCount;self.types=types;self.text=text;self.declaredSource=declaredSource
    }
}

public struct ClipboardObservationSkip:Error,LocalizedError {
    public let reason:String
    public var errorDescription:String? {reason}
    public init(_ reason:String){self.reason=reason}
}

/// This is an observation of text while an app was foreground, not proof that
/// the app produced it. Pasteboard source markers cannot establish authority.
/// Only bounded UTF-8 plain text is admitted; no file, image or rich data is
/// converted. The native reader may have to allocate provider data before it
/// can reject an oversized result; this is not a provider-allocation bound.
public struct ClipboardTextDraft:Sendable {
    public static let collectorID="org.oswind.clipboard"
    public static let maximumTextBytes=65536
    public static let ignoredTypes:Set<String>=[
        "org.nspasteboard.transienttype","org.nspasteboard.concealedtype","org.nspasteboard.autogeneratedtype","org.nspasteboard.restoredtype",
        "de.petermaurer.transientpasteboardtype","com.typeit4me.clipping","pasteboard generator type","com.agilebits.onepassword",
        "com.apple.is-remote-clipboard","public.file-url","public.png","public.tiff","com.adobe.pdf"
    ]
    public let sourceID:String
    public let digest:Data
    public let batch:Data
    public static func admittedTypes(_ types:[String],itemCount:Int)throws {
        guard itemCount==1,types.count<=64,types.allSatisfy({!$0.isEmpty && $0.utf8.count<=256}),types.contains("public.utf8-plain-text"),
              !types.contains(where:{ignoredTypes.contains($0.lowercased())}) else {throw ClipboardObservationSkip("Clipboard format is protected, transient, remote or outside plain-text scope")}
    }
    public static func admittedContext(_ context:WindowContext,policy:PrivacyPolicy)throws {
        guard context.pid>0,!context.secure,!context.bundle.isEmpty,context.bundle.utf8.count<=512,context.app.utf8.count<=512,
              !context.title.isEmpty,context.title.utf8.count<=16384,(context.url?.utf8.count ?? 0)<=8192,
              context.bundle != "com.oswind.desktop",context.bundle != "com.oswind.desktop.demo",
              policy.exclusion(app:context.bundle,title:context.title,url:context.url,isBrowser:context.browser)==nil else {throw ClipboardObservationSkip("Foreground clipboard context is unavailable, protected or excluded")}
    }
    public init(snapshot:ClipboardTextSnapshot,before:WindowContext,after:WindowContext,sessionID:String,at date:Date,elapsedSeconds:Double,policy:PrivacyPolicy)throws {
        try Self.admittedTypes(snapshot.types,itemCount:snapshot.itemCount)
        try Self.admittedContext(before,policy:policy);try Self.admittedContext(after,policy:policy)
        guard UUID(uuidString:sessionID)?.uuidString.lowercased()==sessionID,snapshot.changeCount>=0,snapshot.changeCount==snapshot.finalChangeCount,
              elapsedSeconds.isFinite,elapsedSeconds>=0,elapsedSeconds<=2,date.timeIntervalSince1970.isFinite,
              before.pid==after.pid,Data(before.bundle.utf8)==Data(after.bundle.utf8),Data(before.app.utf8)==Data(after.app.utf8),
              Data(before.title.utf8)==Data(after.title.utf8),before.url.map({Data($0.utf8)})==after.url.map({Data($0.utf8)}),before.bounds==after.bounds else {throw ClipboardObservationSkip("Clipboard or foreground context changed; this observation was discarded")}
        // A matching marker is still only a claim. An absent marker is labeled
        // as unknown origin; an explicitly unknown/mismatched marker refuses.
        if snapshot.types.contains(where:{$0.lowercased()=="org.nspasteboard.source"}) {
            guard let declared=snapshot.declaredSource,!declared.isEmpty,declared.utf8.count<=512,Data(declared.utf8)==Data(before.bundle.utf8) else {throw ClipboardObservationSkip("Clipboard source claim does not match the observed foreground app")}
        }
        guard !snapshot.text.isEmpty,snapshot.text.count<=Self.maximumTextBytes,let text=String(data:snapshot.text,encoding:.utf8),
              !text.utf8.contains(0),!text.trimmingCharacters(in:.whitespacesAndNewlines).isEmpty else {throw ClipboardObservationSkip("Clipboard text is empty, malformed or exceeds64KiB")}
        // Automatic clipboard capture always drops recognized secrets, even
        // when the user disabled pattern redaction for ordinary source imports.
        var detector=policy;detector.redactSecrets=true
        guard !detector.sanitize(text).redacted else {throw ClipboardObservationSkip("Clipboard text matched a secret pattern; nothing was saved")}
        let app=policy.sanitize(before.app).text,title=policy.sanitize(before.title).text,url=policy.sanitize(before.url ?? "").text
        let key=sessionID+"-"+String(snapshot.changeCount)
        sourceID=try TextCollector.sourceID(collectorID:Self.collectorID,key:key)
        digest=Data(SHA256.hash(data:try JSONEncoder().encode(["clipboard-observation-v1",before.bundle,app,title,url,text])))
        let content="""
        Clipboard text observation
        Observed foreground app: \(app)
        Observed window: \(title)
        Clipboard origin is not verified. Foreground app and optional source markers are context, not proof of origin.

        Copied text:
        \(text)
        """
        var record:[String:Any]=["key":key,"app":"Clipboard · "+app,"bundleID":before.bundle,"title":"Clipboard · "+title,"text":content,"timestamp":ISO8601DateFormatter().string(from:date)]
        if !url.isEmpty {record["url"]=url}
        batch=try JSONSerialization.data(withJSONObject:["format":"OSwind collector batch","version":1,"collectorID":Self.collectorID,"records":[record]],options:[.sortedKeys])
    }
}
